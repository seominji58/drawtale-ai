"""## 4. 17→15 joint 변환 + 이미지 단위 train/val/test split"""

import json, random
import numpy as np

COCO_IDX = {n: i for i, n in enumerate([
    "nose", "left_eye", "right_eye", "left_ear", "right_ear",
    "left_shoulder", "right_shoulder", "left_elbow", "right_elbow",
    "left_wrist", "right_wrist", "left_hip", "right_hip",
    "left_knee", "right_knee", "left_ankle", "right_ankle"])}
J15 = ["nose", "neck", "right_shoulder", "right_elbow", "right_wrist",
       "left_shoulder", "left_elbow", "left_wrist", "pelvis",
       "right_hip", "right_knee", "right_ankle", "left_hip", "left_knee", "left_ankle"]
SKEL_1BASED = [[a + 1, b + 1] for a, b in [(0,1),(1,2),(2,3),(3,4),(1,5),(5,6),(6,7),
                                           (1,8),(8,9),(9,10),(10,11),(8,12),(12,13),(13,14)]]

def to15(k17):
    k = np.array(k17, dtype=np.float32).reshape(17, 3)
    g = lambda n: k[COCO_IDX[n]]
    mid = lambda a, b: np.array([(g(a)[0]+g(b)[0])/2, (g(a)[1]+g(b)[1])/2, min(g(a)[2], g(b)[2])])
    return np.stack([g("nose"), mid("left_shoulder", "right_shoulder"),
                     g("right_shoulder"), g("right_elbow"), g("right_wrist"),
                     g("left_shoulder"), g("left_elbow"), g("left_wrist"),
                     mid("left_hip", "right_hip"),
                     g("right_hip"), g("right_knee"), g("right_ankle"),
                     g("left_hip"), g("left_knee"), g("left_ankle")])

raw = json.load(open('/content/amateur_drawings_annotations.json'))
anns = []
for a in raw['annotations']:
    if a.get('num_keypoints', 0) == 0:
        continue
    k = to15(a['keypoints'])
    if (k[:, 2] > 0).sum() < 8:
        continue
    anns.append(dict(id=a['id'], image_id=a['image_id'], bbox=a['bbox'], kpts=k.tolist()))
img_by_id = {im['id']: im for im in raw['images']}
print('annotations:', len(anns))

# 이미지 단위 split (test 5% / val 5% / train 90%)
random.seed(42)
ids = sorted({a['image_id'] for a in anns})
random.shuffle(ids)
nt = int(len(ids) * 0.05)
SPLIT = {'test': set(ids[:nt]), 'val': set(ids[nt:2*nt]), 'train': set(ids[2*nt:])}
SPLIT['smoke_train'] = set(random.sample(sorted(SPLIT['train']), 3000))
SPLIT['smoke_val'] = set(random.sample(sorted(SPLIT['val']), 500))
assert not (SPLIT['train'] & SPLIT['val']) and not (SPLIT['train'] & SPLIT['test']) and not (SPLIT['val'] & SPLIT['test'])
json.dump({k: sorted(v) for k, v in SPLIT.items()}, open(f'{DRIVE}/split_ids.json', 'w'))
print({k: len(v) for k, v in SPLIT.items()})

"""## 5. 이미지 리사이즈(긴 변 ≤1024, JPEG) + COCO json 생성 (좌표 스케일 포함)"""

import os
from PIL import Image
from concurrent.futures import ProcessPoolExecutor

SRC, DST, MAX = '/content/data/', '/content/data_small/', 1024
used = sorted(set().union(*[SPLIT[s] for s in ['train', 'val', 'test']]))

def proc(iid):
    fn0 = img_by_id[iid]['file_name']
    fn = os.path.splitext(fn0)[0] + '.jpg'
    img = Image.open(SRC + fn0)
    w, h = img.size
    s = min(1.0, MAX / max(w, h))
    if not os.path.exists(DST + fn):
        os.makedirs(os.path.dirname(DST + fn), exist_ok=True)
        img = img.convert('RGB')
        if s < 1.0:
            img = img.resize((round(w * s), round(h * s)), Image.BILINEAR)
        img.save(DST + fn, quality=95)
    return iid, (fn, s, round(w * s), round(h * s))

with ProcessPoolExecutor(os.cpu_count()) as ex:
    INFO = dict(ex.map(proc, used, chunksize=256))
print('resized:', len(INFO))

def write_coco(split, dst):
    ids = SPLIT[split]
    out_anns = []
    for a in anns:
        if a['image_id'] not in ids:
            continue
        s = INFO[a['image_id']][1]
        flat, nv = [], 0
        for x, y, v in a['kpts']:
            flat += [x * s, y * s, int(v)]
            nv += int(v > 0)
        bx = [v * s for v in a['bbox']]
        out_anns.append(dict(id=a['id'], image_id=a['image_id'], category_id=1, bbox=bx,
                             area=bx[2] * bx[3], iscrowd=0, keypoints=flat, num_keypoints=nv))
    imgs = [dict(id=i, file_name=INFO[i][0], width=INFO[i][2], height=INFO[i][3]) for i in ids]
    json.dump(dict(images=imgs, annotations=out_anns,
                   categories=[dict(id=1, name='human', supercategory='drawing',
                                    keypoints=J15, skeleton=SKEL_1BASED)]), open(dst, 'w'))
    print(f'{dst}: images {len(imgs)} / anns {len(out_anns)}')

for sp in SPLIT:
    write_coco(sp, f'/content/{sp}_coco.json')

